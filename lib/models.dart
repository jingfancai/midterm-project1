// 여행 데이터 — 구조화된 필드와 기존 subtitle 데이터를 함께 지원한다.
// 형식이 틀린 항목은 null을 돌려준다 → 목록에서 빠질 뿐 앱이 멈추지 않는다 (Dart 3 패턴 매칭).
//
// TODO: Item / Note를 내 앱의 비즈니스 명칭으로 바꾼다 (예: Item → Product, Note → Review).
//           필드 이름은 db.json의 키와 같아야 한다.

class Item {
  const Item({
    required this.id,
    required this.title,
    required String subtitle,
    required this.image,
    this.tags = const [],
    this.destination = '',
    this.countryCode = '',
    this.startDate = '',
    this.endDate = '',
    this.favorite = false,
    this.deleted = false,
  }) : _subtitle = subtitle;

  final int id;
  final String title;
  final String _subtitle;
  final String destination;
  final String countryCode;
  final String startDate;
  final String endDate;
  final bool favorite;
  final bool deleted;

  String get subtitle => startDate.isNotEmpty && endDate.isNotEmpty
      ? '${startDate.replaceAll('-', '.')} – ${endDate.replaceAll('-', '.')} · $destination'
      : _subtitle;

  Item copyWith({
    String? title,
    String? destination,
    String? countryCode,
    String? startDate,
    String? endDate,
    bool? favorite,
    bool? deleted,
  }) => Item(
    id: id,
    title: title ?? this.title,
    subtitle: _subtitle,
    image: image,
    tags: tags,
    destination: destination ?? this.destination,
    countryCode: countryCode ?? this.countryCode,
    startDate: startDate ?? this.startDate,
    endDate: endDate ?? this.endDate,
    favorite: favorite ?? this.favorite,
    deleted: deleted ?? this.deleted,
  );

  Map<String, Object> toJson({bool includeId = true}) => {
    if (includeId) 'id': id,
    'title': title,
    'subtitle': subtitle,
    'image': image,
    'tags': tags,
    'destination': destination,
    'countryCode': countryCode.trim().toUpperCase(),
    'startDate': startDate,
    'endDate': endDate,
    'favorite': favorite,
    'deleted': deleted,
  };
  final String image;
  final List<String> tags;

  /// Dart 3 패턴 예: 맵 모양이 맞으면 꺼내고(구조 분해), 아니면 null.
  static Item? fromJson(Object? json) {
    return switch (json) {
      {
        'id': int id,
        'title': String title,
        'subtitle': String subtitle,
        'image': String image,
      } =>
        Item(
          id: id,
          title: title,
          subtitle: subtitle,
          image: image,
          // 있어도 되고 없어도 되는 필드: 모양이 다르면 빈 목록
          destination: json['destination'] is String
              ? json['destination'] as String
              : '',
          countryCode: json['countryCode'] is String
              ? (json['countryCode'] as String).trim().toUpperCase()
              : '',
          startDate: json['startDate'] is String
              ? json['startDate'] as String
              : '',
          endDate: json['endDate'] is String ? json['endDate'] as String : '',
          favorite: json['favorite'] == true,
          deleted: json['deleted'] == true,
          tags: switch (json['tags']) {
            List<Object?> t => t.whereType<String>().toList(),
            _ => const [],
          },
        ),
      _ => null,
    };
  }
}

class Note {
  const Note({
    required this.id,
    required this.itemId,
    required this.text,
    required this.date,
  });

  final int id;
  final int itemId;
  final String text;
  final String date;

  static Note? fromJson(Object? json) {
    return switch (json) {
      {
        'id': int id,
        'itemId': int itemId,
        'text': String text,
        'date': String date,
      } =>
        Note(id: id, itemId: itemId, text: text, date: date),
      _ => null,
    };
  }
}

